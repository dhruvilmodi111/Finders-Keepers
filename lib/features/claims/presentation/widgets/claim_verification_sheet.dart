import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../../../core/constants/app_colors.dart';
import '../../../auth/presentation/controllers/auth_controller.dart';
import '../../../items/domain/models/item_model.dart';
import '../../domain/models/claim_model.dart';
import '../../domain/services/verification_questions.dart';
import '../controllers/claim_controller.dart';

class ClaimVerificationSheet extends ConsumerStatefulWidget {
  final ItemModel item;

  const ClaimVerificationSheet({
    super.key,
    required this.item,
  });

  @override
  ConsumerState<ClaimVerificationSheet> createState() =>
      _ClaimVerificationSheetState();
}

class _ClaimVerificationSheetState
    extends ConsumerState<ClaimVerificationSheet> {
  final _formKey = GlobalKey<FormState>();
  final _q1Controller = TextEditingController();
  final _q2Controller = TextEditingController();
  bool _isSubmitting = false;

  @override
  void dispose() {
    _q1Controller.dispose();
    _q2Controller.dispose();
    super.dispose();
  }

  Future<void> _submitClaim() async {
    if (!_formKey.currentState!.validate()) return;

    final currentUser = ref.read(currentUserProvider);
    if (currentUser == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Please sign in with your VIT account to submit a claim.')),
      );
      return;
    }

    setState(() => _isSubmitting = true);

    final q1Text = VerificationQuestions.getCategoryQuestion(widget.item.category);
    final q2Text = VerificationQuestions.getHiddenDetailQuestion();

    final claim = ClaimModel(
      id: '', // Generated by repo
      itemId: widget.item.id,
      itemTitle: widget.item.title,
      itemOwnerId: widget.item.ownerId,
      claimerId: currentUser.id,
      claimerAlias: 'VIT Student #${currentUser.id.substring(0, 4).toUpperCase()}',
      answers: {
        'question1': q1Text,
        'answer1': _q1Controller.text.trim(),
        'question2': q2Text,
        'answer2': _q2Controller.text.trim(),
      },
      status: ClaimStatus.pending,
      createdAt: DateTime.now(),
    );

    final claimId = await ref
        .read(claimControllerProvider.notifier)
        .submitClaim(claim);

    if (mounted) {
      setState(() => _isSubmitting = false);

      if (claimId != null) {
        Navigator.of(context).pop();
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Row(
              children: [
                Icon(Icons.check_circle, color: Colors.white, size: 18),
                SizedBox(width: 8),
                Expanded(
                  child: Text(
                    'Claim submitted! The finder will review your answers in their Claims Inbox.',
                  ),
                ),
              ],
            ),
            backgroundColor: AppColors.statusFound,
            duration: Duration(seconds: 4),
          ),
        );
      } else {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Failed to submit claim. Please try again.'),
            backgroundColor: AppColors.statusLost,
          ),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final q1 = VerificationQuestions.getCategoryQuestion(widget.item.category);
    final q2 = VerificationQuestions.getHiddenDetailQuestion();

    return Padding(
      padding: EdgeInsets.only(
        bottom: MediaQuery.of(context).viewInsets.bottom,
      ),
      child: Container(
        decoration: BoxDecoration(
          color: theme.colorScheme.surface,
          borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
        ),
        padding: const EdgeInsets.fromLTRB(24, 16, 24, 28),
        child: SingleChildScrollView(
          child: Form(
            key: _formKey,
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                // Handle
                Center(
                  child: Container(
                    width: 36,
                    height: 4,
                    decoration: BoxDecoration(
                      color: Colors.grey.withOpacity(0.35),
                      borderRadius: BorderRadius.circular(2),
                    ),
                  ),
                ),
                const SizedBox(height: 16),

                // Header
                Row(
                  children: [
                    Container(
                      padding: const EdgeInsets.all(8),
                      decoration: BoxDecoration(
                        color: AppColors.primaryTeal.withOpacity(0.12),
                        shape: BoxShape.circle,
                      ),
                      child: const Icon(
                        Icons.verified_user_rounded,
                        color: AppColors.primaryTeal,
                        size: 24,
                      ),
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                            'Claim Verification',
                            style: theme.textTheme.titleMedium?.copyWith(
                              fontWeight: FontWeight.bold,
                            ),
                          ),
                          Text(
                            widget.item.title,
                            style: theme.textTheme.bodySmall?.copyWith(
                              color: AppColors.lightTextSecondary,
                            ),
                            maxLines: 1,
                            overflow: TextOverflow.ellipsis,
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 14),

                // Privacy assurance note
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
                  decoration: BoxDecoration(
                    color: AppColors.primaryTeal.withOpacity(0.08),
                    borderRadius: BorderRadius.circular(10),
                    border: Border.all(color: AppColors.primaryTeal.withOpacity(0.2)),
                  ),
                  child: Row(
                    children: const [
                      Icon(Icons.lock_outline, size: 15, color: AppColors.primaryTeal),
                      SizedBox(width: 8),
                      Expanded(
                        child: Text(
                          'In-App Verification Only • Phone numbers & emails are never exposed to maintain campus privacy.',
                          style: TextStyle(fontSize: 11, fontWeight: FontWeight.w500),
                        ),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 20),

                // Question 1: Category Specific
                Text(
                  'Question 1 (${widget.item.category})',
                  style: theme.textTheme.labelLarge?.copyWith(
                    color: AppColors.primaryTeal,
                    fontWeight: FontWeight.bold,
                  ),
                ),
                const SizedBox(height: 4),
                Text(
                  q1,
                  style: theme.textTheme.bodyMedium?.copyWith(
                    fontWeight: FontWeight.w500,
                  ),
                ),
                const SizedBox(height: 8),
                TextFormField(
                  controller: _q1Controller,
                  maxLines: 2,
                  decoration: const InputDecoration(
                    hintText: 'Provide specific identifying details...',
                  ),
                  validator: (val) {
                    if (val == null || val.trim().isEmpty) {
                      return 'Please answer Question 1 to verify ownership';
                    }
                    return null;
                  },
                ),
                const SizedBox(height: 20),

                // Question 2: Hidden Detail Prompt
                Text(
                  'Question 2 (Secret Identifier)',
                  style: theme.textTheme.labelLarge?.copyWith(
                    color: AppColors.accentAmberDark,
                    fontWeight: FontWeight.bold,
                  ),
                ),
                const SizedBox(height: 4),
                Text(
                  q2,
                  style: theme.textTheme.bodyMedium?.copyWith(
                    fontWeight: FontWeight.w500,
                  ),
                ),
                const SizedBox(height: 8),
                TextFormField(
                  controller: _q2Controller,
                  maxLines: 2,
                  decoration: const InputDecoration(
                    hintText: 'Answer the secret detail noted by the finder...',
                  ),
                  validator: (val) {
                    if (val == null || val.trim().isEmpty) {
                      return 'Please provide the secret detail answer';
                    }
                    return null;
                  },
                ),
                const SizedBox(height: 26),

                // Submit Claim Button
                SizedBox(
                  width: double.infinity,
                  child: ElevatedButton(
                    onPressed: _isSubmitting ? null : _submitClaim,
                    child: _isSubmitting
                        ? const SizedBox(
                            width: 20,
                            height: 20,
                            child: CircularProgressIndicator(
                              strokeWidth: 2,
                              color: Colors.white,
                            ),
                          )
                        : const Text('Submit Ownership Claim'),
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
